static void draw_app_handler(char e) {
    char i;
    switch(e) {
        case WINDOW_EVENT_DRAW:
            queue_draw_sprite(my(window_x), my(window_y), DRAW_APP_W, DRAW_APP_H, 0, 0, my(window_sprite));
            break;
        case WINDOW_EVENT_TICK:
            break;
        case WINDOW_EVENT_LATE_TICK:
            direct_prepare_sprite_ram_array_mode(my(window_sprite));
            if(ctx->pending_action == PENDING_ACTION_SAVE_NAME_CLEAR) {
                for(i = 0; i < 8; ++i) {
                    ctx->name_buf[i] = ' ';
                }
                ctx->name_cursor = 0;
                bittext_set_cursor(1, 76);
                bittext_bg = 7;
                bittext_color = 32;
                bittext_write_str_opaque("        .BMP");
                ctx->pending_action = PENDING_ACTION_SAVE_NAME_ENTRY;
            } else if(ctx->pending_action == PENDING_ACTION_SAVE_NAME_ENTRY) {
                if(foreground_app != current_app) break;
                
                bittext_bg = 7;
                bittext_color = 32;
                lineentry_buf = ctx->name_buf;
                lineentry_len = 8;
                lineentry_x = 1;
                lineentry_y = 76;
                lineentry_cursor = &(ctx->name_cursor);
                if(lineentry_update()) {
                    if(fs_validate_filename_no_ext(ctx->name_buf)) {
                        ctx->pending_action = PENDING_ACTION_SAVE;
                    } else {
                        ctx->pending_action = PENDING_ACTION_NONE;
                        bittext_set_cursor(1, 76);
                        bittext_bg = 5;
                        bittext_color = 3;
                        bittext_write_str_opaque("INVALID     ");
                    }
                }
            } else if(ctx->pending_action == PENDING_ACTION_SAVE) {
                ctx->pending_action = PENDING_ACTION_NONE;
                bittext_set_cursor(1, 76);
                bittext_bg = 5;
                bittext_color = 3;
                fs_create_sync(ctx->name_buf);
                if(fs_write_data(bmpHeader, BANK_PROG1, sizeof(bmpHeader), 0, 0) && fs_write_data(vram+8577,BANK_PROG0, 4096, 64, -192) && fs_close_sync()) {
                    bittext_write_str_opaque("SAVED       ");
                } else {
                    bittext_write_str_opaque("ERROR       ");
                }

            } else {
                for(activeMouse = 0; activeMouse < ps2_device_count; ++activeMouse) {
                    if(ps2_device_types[activeMouse] != PS2_DEVICE_TYPE_BASIC_MOUSE) continue;
                    if(drag_in_window[activeMouse] == current_app) {
                        if(subwindow_rect_test()) {
                            vram[((mouse_display_y[activeMouse] - my(window_y)) << 7) + ((mouse_display_x[activeMouse] - my(window_x)) & 0x7F)] = ctx->draw_color[activeMouse];
                        }
                    }
                    if(sample_pixel[activeMouse] == current_app) {
                        sample_pixel[activeMouse] = 0xFF;
                        ctx->draw_color[activeMouse] = vram[((mouse_display_y[activeMouse] - my(window_y)) << 7) + ((mouse_display_x[activeMouse] - my(window_x)) & 0x7F)];
                    }
                }
            }    
            flagsMirror |= DMA_ENABLE;
            *dma_flags = flagsMirror;
            break;
        case WINDOW_EVENT_MOUSE_CLICK:
            if(ctx->pending_action == PENDING_ACTION_NONE) {
                if((mouse_display_y[activeMouse] - my(window_y) > 69)) {
                    if((mouse_display_x[activeMouse] - my(window_x) > 54)) {
                        ctx->pending_action = PENDING_ACTION_SAVE_NAME_CLEAR;
                        
                    } else {
                        sample_pixel[activeMouse] = current_app;
                    }
                } else {
                    drag_in_window[activeMouse] = current_app;
                }
            }
            break;
        case WINDOW_EVENT_MOUSE_RELEASE:
            drag_in_window[activeMouse] = 0xFF;
            break;
        case WINDOW_EVENT_EXIT:
            free_sprite(my(window_sprite));
            mem_free(my(window_context));
            --draw_app_open_count;
            break;
        default:
            break;
    }
}

void draw_app_launch() {
    if(desktop_launch_app(draw_app_handler) != 255) {
        my(window_context) = mem_alloc(sizeof(draw_app_context));
        my(window_sprite) = allocate_sprite(&ASSET__gfx__draw_bmp_load_list);
        my(window_x) = 32 + (draw_app_open_count<<2);
        my(window_y) = 24 + (draw_app_open_count<<2);
        my(window_w) = DRAW_APP_W;
        my(window_h) = DRAW_APP_H;
        ctx->pending_action = PENDING_ACTION_NONE;
        ctx->name_buf[8] = '.';
        ctx->name_buf[9] = 'B';
        ctx->name_buf[10] = 'M';
        ctx->name_buf[11] = 'P';
        ctx->name_buf[12] = 0;

        for(activeMouse = 0; activeMouse < ps2_device_count; ++activeMouse) {
            ctx->draw_color[activeMouse] = 32;
        }
        ++draw_app_open_count;
    }
}